#!/usr/bin/env node
/**
 * Generates docs/dependency-status.md from npm outdated + npm audit.
 * Intentionally omits a wall-clock timestamp so weekly runs do not create
 * empty commits when the dependency picture is unchanged.
 */
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(root, "docs", "dependency-status.md");

function runJson(command) {
  try {
    const stdout = execSync(command, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
    return stdout.trim() ? JSON.parse(stdout) : {};
  } catch (error) {
    // npm outdated exits 1 when outdated packages exist
    // npm audit exits non-zero when vulnerabilities exist
    const stdout = error.stdout?.toString?.() ?? "";
    if (!stdout.trim()) return {};
    try {
      return JSON.parse(stdout);
    } catch {
      return {};
    }
  }
}

const outdated = runJson("npm outdated --json");
const audit = runJson("npm audit --json");

const outdatedRows = Object.entries(outdated)
  .map(([name, info]) => {
    const current = info.current ?? "—";
    const wanted = info.wanted ?? "—";
    const latest = info.latest ?? "—";
    const type = info.type ?? "—";
    return `| \`${name}\` | ${current} | ${wanted} | ${latest} | ${type} |`;
  })
  .sort((a, b) => a.localeCompare(b));

const vuln = audit.metadata?.vulnerabilities ?? {};
const totalVulns =
  (vuln.info ?? 0) +
  (vuln.low ?? 0) +
  (vuln.moderate ?? 0) +
  (vuln.high ?? 0) +
  (vuln.critical ?? 0);

const lines = [
  "# Dependency status",
  "",
  "Auto-generated by `.github/workflows/weekly-maintenance.yml`.",
  "Committed only when this content changes.",
  "",
  "## Audit summary",
  "",
  `| Severity | Count |`,
  `| --- | ---: |`,
  `| Critical | ${vuln.critical ?? 0} |`,
  `| High | ${vuln.high ?? 0} |`,
  `| Moderate | ${vuln.moderate ?? 0} |`,
  `| Low | ${vuln.low ?? 0} |`,
  `| Info | ${vuln.info ?? 0} |`,
  `| **Total** | **${totalVulns}** |`,
  "",
  "## Outdated packages",
  "",
];

if (outdatedRows.length === 0) {
  lines.push("_All dependencies match the wanted range._", "");
} else {
  lines.push(
    "| Package | Current | Wanted | Latest | Type |",
    "| --- | --- | --- | --- | --- |",
    ...outdatedRows,
    ""
  );
}

lines.push(
  "## Notes",
  "",
  "- Prefer Dependabot PRs for upgrades; review before merging.",
  "- This report is portfolio maintenance metadata, not a substitute for CI.",
  ""
);

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(`Wrote ${outPath}`);
